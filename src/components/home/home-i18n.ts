/** Profile/link content exists only in English and Vietnamese; other locales read the English edition. */
export function profileContentLocale(locale: Locale): 'en' | 'vi' {
  return locale === 'vi' ? 'vi' : 'en';
}

/** Replaces `{name}` placeholders. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_m, key: string) => (key in vars ? String(vars[key]) : `{${key}}`));
}

